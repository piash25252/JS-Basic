
function sum(a,b)
{
    const result = a+b;
    return result;
}

function sub(a,b)
{
    const result = a-b;
    return result;
}

function multiply(a,b)
{
    const result = a*b;
    return result;
}

function div(a,b)
{
    const result = a/b;
    return result;
}

console.log(`Result of sum(6,2) is ${sum(6,2)}`);
console.log(`Result of sub(6,2) is ${sub(6,2)}`);
console.log(`Result of multiply(6,2) is ${multiply(6,2)}`);
console.log(`Result of div(6,2) is ${div(6,2)}`);
